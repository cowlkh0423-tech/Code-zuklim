// 조작
// ↑ : 위
// ↓ : 아래
// ← : 왼쪽
// → : 오른쪽
//
// 체력은 1개.
// 한 번 화살에 맞으면 즉시 사망.
// ============================================================


export class Player {

    constructor(x, y) {

        // ----------------------------------------------------
        // 위치
        // ----------------------------------------------------

        this.x = x;
        this.y = y;

        this.previousX = x;
        this.previousY = y;


        // ----------------------------------------------------
        // 크기
        // ----------------------------------------------------

        this.radius = 14;


        // ----------------------------------------------------
        // 이동
        // ----------------------------------------------------

        this.speed = 260;

        this.velocityX = 0;
        this.velocityY = 0;


        // ----------------------------------------------------
        // 체력
        // ----------------------------------------------------

        this.maxHealth = 1;
        this.health = 1;


        // ----------------------------------------------------
        // 애니메이션
        // ----------------------------------------------------

        this.animationTime = 0;


        // ----------------------------------------------------
        // 피격 효과
        // ----------------------------------------------------

        this.hitFlash = 0;

    }


    // ========================================================
    // 플레이어 초기화
    // ========================================================

    reset(x, y) {

        this.x = x;
        this.y = y;

        this.previousX = x;
        this.previousY = y;

        this.velocityX = 0;
        this.velocityY = 0;

        this.health = 1;

        this.animationTime = 0;

        this.hitFlash = 0;

    }


    // ========================================================
    // 업데이트
    // ========================================================

    update(
        delta,
        keys,
        width,
        height
    ) {

        // ----------------------------------------------------
        // 이전 위치
        // ----------------------------------------------------

        this.previousX = this.x;
        this.previousY = this.y;


        // ----------------------------------------------------
        // 이동 방향
        // ----------------------------------------------------

        let directionX = 0;
        let directionY = 0;


        // ====================================================
        // 방향키
        // ====================================================

        if (keys["ArrowUp"]) {

            directionY -= 1;

        }


        if (keys["ArrowDown"]) {

            directionY += 1;

        }


        if (keys["ArrowLeft"]) {

            directionX -= 1;

        }


        if (keys["ArrowRight"]) {

            directionX += 1;

        }


        // ----------------------------------------------------
        // 대각선 이동 속도 보정
        // ----------------------------------------------------

        const length = Math.sqrt(
            directionX * directionX +
            directionY * directionY
        );


        if (length > 0) {

            directionX /= length;
            directionY /= length;

        }


        // ----------------------------------------------------
        // 목표 속도
        // ----------------------------------------------------

        const targetVelocityX =
            directionX * this.speed;

        const targetVelocityY =
            directionY * this.speed;


        // ----------------------------------------------------
        // 부드러운 가속
        // ----------------------------------------------------

        const acceleration = 14;


        this.velocityX += (
            targetVelocityX -
            this.velocityX
        ) * Math.min(
            1,
            acceleration * delta
        );


        this.velocityY += (
            targetVelocityY -
            this.velocityY
        ) * Math.min(
            1,
            acceleration * delta
        );


        // ----------------------------------------------------
        // 이동
        // ----------------------------------------------------

        this.x +=
            this.velocityX * delta;

        this.y +=
            this.velocityY * delta;


        // ----------------------------------------------------
        // 화면 밖으로 나가지 못하게 함
        // ----------------------------------------------------

        this.x = Math.max(
            this.radius,
            Math.min(
                width - this.radius,
                this.x
            )
        );


        this.y = Math.max(
            this.radius,
            Math.min(
                height - this.radius,
                this.y
            )
        );


        // ----------------------------------------------------
        // 애니메이션 시간
        // ----------------------------------------------------

        this.animationTime += delta;


        // ----------------------------------------------------
        // 피격 효과
        // ----------------------------------------------------

        if (this.hitFlash > 0) {

            this.hitFlash -= delta;

        }

    }


    // ========================================================
    // 피격
    // ========================================================

    takeDamage() {

        if (this.health <= 0) {

            return;

        }


        // 목숨은 하나뿐
        this.health = 0;


        // 피격 효과
        this.hitFlash = 0.3;

    }


    // ========================================================
    // 움직이는 중인지 확인
    // ========================================================

    isMoving() {

        return (
            Math.abs(this.velocityX) > 5 ||
            Math.abs(this.velocityY) > 5
        );

    }


    // ========================================================
    // 플레이어 그리기
    // ========================================================

    draw(ctx) {

        const moving =
            this.isMoving();


        // ----------------------------------------------------
        // 움직일 때 살짝 흔들림
        // ----------------------------------------------------

        const bob = moving
            ? Math.sin(
                this.animationTime * 14
            ) * 1.5
            : 0;


        const x = this.x;
        const y = this.y + bob;


        // ====================================================
        // 그림자
        // ====================================================

        ctx.save();

        ctx.globalAlpha = 0.35;

        ctx.fillStyle = "#000000";

        ctx.beginPath();

        ctx.ellipse(
            x,
            y + 17,
            19,
            7,
            0,
            0,
            Math.PI * 2
        );

        ctx.fill();

        ctx.restore();


        // ====================================================
        // 피격 효과
        // ====================================================

        if (this.hitFlash > 0) {

            ctx.save();

            ctx.globalAlpha = 0.75;

            ctx.fillStyle = "#ff453a";

            ctx.shadowColor = "#ff453a";

            ctx.shadowBlur = 20;

            ctx.beginPath();

            ctx.arc(
                x,
                y,
                this.radius + 9,
                0,
                Math.PI * 2
            );

            ctx.fill();

            ctx.restore();

        }


        // ====================================================
        // 캐릭터
        // ====================================================

        ctx.save();


        // ----------------------------------------------------
        // 황금색 외곽광
        // ----------------------------------------------------

        ctx.shadowColor =
            "rgba(225, 190, 80, 0.45)";

        ctx.shadowBlur = 12;


        // ----------------------------------------------------
        // 몸
        // ----------------------------------------------------

        ctx.fillStyle = "#3d613f";

        ctx.beginPath();

        ctx.ellipse(
            x,
            y + 7,
            13,
            15,
            0,
            0,
            Math.PI * 2
        );

        ctx.fill();


        // ----------------------------------------------------
        // 얼굴
        // ----------------------------------------------------

        ctx.shadowBlur = 0;

        ctx.fillStyle = "#dcb47b";

        ctx.beginPath();

        ctx.arc(
            x,
            y - 5,
            9,
            0,
            Math.PI * 2
        );

        ctx.fill();


        // ====================================================
        // 삿갓
        // ====================================================

        ctx.fillStyle = "#735a32";

        ctx.beginPath();

        ctx.moveTo(
            x,
            y - 27
        );

        ctx.lineTo(
            x - 21,
            y - 6
        );

        ctx.lineTo(
            x + 21,
            y - 6
        );

        ctx.closePath();

        ctx.fill();


        // ----------------------------------------------------
        // 삿갓 테두리
        // ----------------------------------------------------

        ctx.strokeStyle = "#382a17";

        ctx.lineWidth = 2;

        ctx.stroke();


        // ----------------------------------------------------
        // 얼굴 그림자
        // ----------------------------------------------------

        ctx.fillStyle =
            "rgba(45, 31, 17, 0.35)";

        ctx.beginPath();

        ctx.arc(
            x,
            y - 5,
            8,
            Math.PI,
            Math.PI * 2
        );

        ctx.fill();


        // ====================================================
        // 눈
        // ====================================================

        ctx.fillStyle = "#17130c";

        ctx.fillRect(
            x - 4,
            y - 5,
            2,
            2
        );

        ctx.fillRect(
            x + 2,
            y - 5,
            2,
            2
        );


        // ====================================================
        // 옷 장식
        // ====================================================

        ctx.strokeStyle = "#c3a34f";

        ctx.lineWidth = 1;

        ctx.beginPath();

        ctx.moveTo(
            x,
            y + 1
        );

        ctx.lineTo(
            x,
            y + 16
        );

        ctx.stroke();


        // ====================================================
        // 복장 허리띠
        // ====================================================

        ctx.strokeStyle = "#a88a42";

        ctx.lineWidth = 2;

        ctx.beginPath();

        ctx.moveTo(
            x - 10,
            y + 8
        );

        ctx.lineTo(
            x + 10,
            y + 8
        );

        ctx.stroke();


        ctx.restore();

    }

}
