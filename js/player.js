// player.js
//
// 플레이어 담당
//
// 조작:
// W = 위
// A = 왼쪽
// S = 아래
// D = 오른쪽
//
// 그 외 기능 없음.
// ============================================================


export class Player {


    // ========================================================
    // 생성
    // ========================================================

    constructor(x, y) {

        // ----------------------------------------------------
        // 위치
        // ----------------------------------------------------

        this.x = x;
        this.y = y;


        // ----------------------------------------------------
        // 이전 위치
        // ----------------------------------------------------

        this.previousX = x;
        this.previousY = y;


        // ----------------------------------------------------
        // 크기
        // ----------------------------------------------------

        this.radius = 14;


        // ----------------------------------------------------
        // 이동 속도
        // ----------------------------------------------------

        this.speed = 240;


        // ----------------------------------------------------
        // 체력
        // ----------------------------------------------------

        this.maxHealth = 1;

        this.health = 1;


        // ----------------------------------------------------
        // 부드러운 움직임
        // ----------------------------------------------------

        this.velocityX = 0;
        this.velocityY = 0;


        // ----------------------------------------------------
        // 애니메이션
        // ----------------------------------------------------

        this.animationTime = 0;


        // ----------------------------------------------------
        // 피격 효과
        // ----------------------------------------------------

        this.hitFlash = 0;

    }


    // ========================================================
    // 초기화
    // ========================================================

    reset(x, y) {

        this.x = x;
        this.y = y;

        this.previousX = x;
        this.previousY = y;

        this.velocityX = 0;
        this.velocityY = 0;

        this.health = 1;

        this.animationTime = 0;

        this.hitFlash = 0;

    }


    // ========================================================
    // 업데이트
    // ========================================================

    update(
        delta,
        keys,
        width,
        height
    ) {

        // ----------------------------------------------------
        // 이전 위치 저장
        // ----------------------------------------------------

        this.previousX =
            this.x;

        this.previousY =
            this.y;


        // ----------------------------------------------------
        // 이동 방향
        // ----------------------------------------------------

        let directionX = 0;
        let directionY = 0;


        // ----------------------------------------------------
        // W
        // ----------------------------------------------------

        if (
            keys["w"] ||
            keys["W"]
        ) {

            directionY -= 1;

        }


        // ----------------------------------------------------
        // S
        // ----------------------------------------------------

        if (
            keys["s"] ||
            keys["S"]
        ) {

            directionY += 1;

        }


        // ----------------------------------------------------
        // A
        // ----------------------------------------------------

        if (
            keys["a"] ||
            keys["A"]
        ) {

            directionX -= 1;

        }


        // ----------------------------------------------------
        // D
        // ----------------------------------------------------

        if (
            keys["d"] ||
            keys["D"]
        ) {

            directionX += 1;

        }


        // ----------------------------------------------------
        // 대각선 속도 보정
        // ----------------------------------------------------

        const length =
            Math.sqrt(
                directionX *
                directionX +

                directionY *
                directionY
            );


        if (
            length > 0
        ) {

            directionX /=
                length;

            directionY /=
                length;

        }


        // ----------------------------------------------------
        // 목표 속도
        // ----------------------------------------------------

        const targetVelocityX =
            directionX *
            this.speed;


        const targetVelocityY =
            directionY *
            this.speed;


        // ----------------------------------------------------
        // 가속
        // ----------------------------------------------------

        const acceleration =
            12;


        this.velocityX +=
            (
                targetVelocityX -
                this.velocityX
            ) *
            Math.min(
                1,
                acceleration *
                delta
            );


        this.velocityY +=
            (
                targetVelocityY -
                this.velocityY
            ) *
            Math.min(
                1,
                acceleration *
                delta
            );


        // ----------------------------------------------------
        // 이동
        // ----------------------------------------------------

        this.x +=
            this.velocityX *
            delta;


        this.y +=
            this.velocityY *
            delta;


        // ----------------------------------------------------
        // 화면 경계
        // ----------------------------------------------------

        this.x =
            Math.max(
                this.radius,
                Math.min(
                    width -
                    this.radius,

                    this.x
                )
            );


        this.y =
            Math.max(
                this.radius,
                Math.min(
                    height -
                    this.radius,

                    this.y
                )
            );


        // ----------------------------------------------------
        // 애니메이션
        // ----------------------------------------------------

        this.animationTime +=
            delta;


        // ----------------------------------------------------
        // 피격 효과 감소
        // ----------------------------------------------------

        if (
            this.hitFlash > 0
        ) {

            this.hitFlash -=
                delta;

        }

    }


    // ========================================================
    // 데미지
    // ========================================================

    takeDamage() {

        if (
            this.health <= 0
        ) {

            return;

        }


        // ----------------------------------------------------
        // 체력은 단 하나
        // ----------------------------------------------------

        this.health = 0;


        // ----------------------------------------------------
        // 피격 효과
        // ----------------------------------------------------

        this.hitFlash = 0.25;

    }


    // ========================================================
    // 이동 중인지 확인
    // ========================================================

    isMoving() {

        return (
            Math.abs(
                this.velocityX
            ) > 5 ||

            Math.abs(
                this.velocityY
            ) > 5
        );

    }


    // ========================================================
    // 플레이어 그리기
    // ========================================================

    draw(ctx) {

        // ----------------------------------------------------
        // 걷는 애니메이션
        // ----------------------------------------------------

        const moving =
            this.isMoving();


        const bob =
            moving

                ? Math.sin(
                    this.animationTime *
                    14
                ) * 1.5

                : 0;


        const x =
            this.x;

        const y =
            this.y + bob;


        // ----------------------------------------------------
        // 그림자
        // ----------------------------------------------------

        ctx.save();


        ctx.globalAlpha =
            0.35;


        ctx.fillStyle =
            "#000000";


        ctx.beginPath();

        ctx.ellipse(
            x,
            y + 14,
            18,
            7,
            0,
            0,
            Math.PI * 2
        );

        ctx.fill();


        ctx.restore();


        // ----------------------------------------------------
        // 피격 상태
        // ----------------------------------------------------

        if (
            this.hitFlash > 0
        ) {

            ctx.save();

            ctx.globalAlpha =
                0.8;

            ctx.fillStyle =
                "#ff453a";

            ctx.beginPath();

            ctx.arc(
                x,
                y,
                this.radius + 8,
                0,
                Math.PI * 2
            );

            ctx.fill();

            ctx.restore();

        }


        // ----------------------------------------------------
        // 캐릭터 본체
        // ----------------------------------------------------

        ctx.save();


        // 외곽광

        ctx.shadowColor =
            "rgba(226, 194, 91, 0.35)";

        ctx.shadowBlur = 10;


        // 옷

        ctx.fillStyle =
            "#3c613d";


        ctx.beginPath();

        ctx.ellipse(
            x,
            y + 7,
            13,
            15,
            0,
            0,
            Math.PI * 2
        );

        ctx.fill();


        // ----------------------------------------------------
        // 얼굴
        // ----------------------------------------------------

        ctx.shadowBlur = 0;

        ctx.fillStyle =
            "#dcb47b";


        ctx.beginPath();

        ctx.arc(
            x,
            y - 5,
            9,
            0,
            Math.PI * 2
        );

        ctx.fill();


        // ----------------------------------------------------
        // 삿갓
        // ----------------------------------------------------

        ctx.fillStyle =
            "#715932";


        ctx.beginPath();

        ctx.moveTo(
            x,
            y - 26
        );

        ctx.lineTo(
            x - 20,
            y - 6
        );

        ctx.lineTo(
            x + 20,
            y - 6
        );

        ctx.closePath();

        ctx.fill();


        // ----------------------------------------------------
        // 삿갓 테두리
        // ----------------------------------------------------

        ctx.strokeStyle =
            "#392c18";

        ctx.lineWidth = 2;

        ctx.stroke();


        // ----------------------------------------------------
        // 얼굴 그늘
        // ----------------------------------------------------

        ctx.fillStyle =
            "rgba(45, 31, 17, 0.35)";


        ctx.beginPath();

        ctx.arc(
            x,
            y - 5,
            8,
            Math.PI,
            Math.PI * 2
        );

        ctx.fill();


        // ----------------------------------------------------
        // 눈
        // ----------------------------------------------------

        ctx.fillStyle =
            "#17130c";


        ctx.fillRect(
            x - 4,
            y - 5,
            2,
            2
        );


        ctx.fillRect(
            x + 2,
            y - 5,
            2,
            2
        );


        // ----------------------------------------------------
        // 몸 중앙 장식
        // ----------------------------------------------------

        ctx.strokeStyle =
            "#b59a4d";

        ctx.lineWidth = 1;


        ctx.beginPath();

        ctx.moveTo(
            x,
            y + 1
        );

        ctx.lineTo(
            x,
            y + 15
        );

        ctx.stroke();


        ctx.restore();

    }

}
